// 反查：給一個 pattern 字串，回傳它屬於的 tags 陣列
function getGrammarTags(pattern) {
  const tags = [];
  for (const [tag, list] of Object.entries(GRAMMAR_TAGS)) {
    if (list.includes(pattern)) tags.push(tag);
  }
  return tags;
}

// 統計：某 tag 涵蓋多少現有 grammar pattern
function getTagCoverage(grammarData) {
  const result = {};
  for (const tag of GRAMMAR_TAG_ORDER) result[tag] = 0;
  for (const entry of grammarData) {
    for (const tag of getGrammarTags(entry.pattern)) {
      result[tag] = (result[tag] || 0) + 1;
    }
  }
  return result;
}

